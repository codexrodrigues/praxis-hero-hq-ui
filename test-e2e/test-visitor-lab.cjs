const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium, expect } = require(require.resolve('@playwright/test', { paths: [__dirname, path.resolve(__dirname, '../../praxis-ui-angular/node_modules')] }));
const BASE = 'http://127.0.0.1:4302';
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const writes = [];
  page.on('pageerror', error => console.error('Browser error:', error.message));
  await context.route('**/api/**', async (route) => {
    const request = route.request();
    if (page.url().includes('/laboratorio') && request.url().includes('/praxis/config/') && !['GET','OPTIONS'].includes(request.method())) writes.push(request.url());
    await route.fulfill({ status: request.url().includes('/praxis/config/ui') ? 404 : 200, json: { data: { buckets: [] } } });
  });
  try {
    await page.goto(`${BASE}/comando-studio`);
    await page.getByRole('button', { name: 'Inserir componente', exact: true }).click();
    await page.getByTestId('component-palette-search').fill('praxis-dynamic-form');
    await page.getByRole('button', { name: 'Adicionar Praxis Dynamic Form', exact: true }).click();
    await page.locator('.pdx-widget').waitFor();
    await page.getByRole('button', { name: 'Configurar conteúdo', exact: true }).click();
    await page.getByRole('combobox', { name: 'Seção do editor' }).click();
    await page.getByRole('option', { name: 'JSON', exact: true }).click();
    const document = JSON.parse(await page.locator('textarea').inputValue());
    document.config.sections = [{ id: 'contact', title: 'Contato do visitante', rows: [{ id: 'row', columns: [{ id: 'column', fields: ['nome'], items: [{ id: 'field-nome', kind: 'field', fieldName: 'nome' }] }] }] }];
    document.config.fieldMetadata = [{ name: 'nome', label: 'Nome do visitante', controlType: 'input', dataType: 'string', source: 'local', submitPolicy: 'omit' }];
    await page.locator('textarea').fill(JSON.stringify(document, null, 2));
    const applyJson = page.getByRole('button', { name: 'Aplicar JSON', exact: true });
    await expect(applyJson).toBeEnabled();
    await applyJson.focus();
    await applyJson.press('Enter');
    await page.getByRole('button', { name: 'Salvar e fechar', exact: true }).click();
    await page.getByTestId('studio-copy-to-lab').click();
    await expect(page).toHaveURL(`${BASE}/laboratorio`);
    await expect(page.getByLabel('Nome do visitante', { exact: true })).toBeVisible();
    await page.getByTestId('lab-page-name').fill('Meu painel local');
    await page.getByTestId('lab-menu-name').fill('Meu comando');
    await page.getByTestId('lab-menu-icon').click();
    await page.getByRole('option', { name: 'Formulário', exact: false }).click();
    await page.getByTestId('lab-save').click();
    const link = page.getByTestId('lab-saved-link');
    await link.waitFor({ state: 'visible', timeout: 15000 });
    const savedPath = await link.getAttribute('href');
    assert.match(savedPath, /^\/laboratorio\/paginas\/[0-9a-f-]{36}$/);
    // A quota failure must keep the last acknowledged link, document and draft.
    await page.evaluate(() => {
      window.originalLabSetItem = Storage.prototype.setItem;
      Storage.prototype.setItem = function(key, value) {
        if (key.startsWith('hero-hq:visitor-lab:')) throw new DOMException('Quota', 'QuotaExceededError');
        return window.originalLabSetItem.call(this, key, value);
      };
    });
    await page.getByTestId('lab-page-name').fill('Rascunho após falha');
    await page.getByTestId('lab-save').click();
    await page.getByRole('alert').filter({ hasText: 'Não foi possível acessar' }).waitFor();
    assert.equal(await link.getAttribute('href'), savedPath);
    await expect(page.getByTestId('lab-page-name')).toHaveValue('Rascunho após falha');
    await page.evaluate(() => { Storage.prototype.setItem = window.originalLabSetItem; delete window.originalLabSetItem; });
    await link.click();
    await expect(page).toHaveURL(`${BASE}${savedPath}`);
    await expect(page.getByTestId('lab-page-name')).toHaveValue('Meu painel local');
    await page.reload();
    await expect(page.getByTestId('lab-page-name')).toHaveValue('Meu painel local');
    assert.equal(await page.locator('praxis-dynamic-page-builder .pdx-widget').count(), 1);
    await expect(page.getByLabel('Nome do visitante', { exact: true })).toBeVisible();
    const state = await page.evaluate(() => {
      const key = Object.keys(localStorage).find(key => key.startsWith('hero-hq:visitor-lab:v1:'));
      return { key, value: JSON.parse(localStorage.getItem(key)) };
    });
    assert.equal(state.value.pages.length, 1);
    assert.equal(state.value.menus[0].label, 'Meu comando');
    assert.equal(state.value.menus[0].items[0].pageId, state.value.pages[0].id);
    assert.equal(state.value.menus[0].items[0].icon, 'assignment');
    await expect(page.getByTestId('lab-menu-icon')).toContainText('Formulário');
    await expect(page.locator('.praxis-shell__nav').getByRole('link', { name: /Meu painel local/ }).locator('.material-symbols-outlined')).toHaveText('assignment');
    const raw = await page.evaluate(key => localStorage.getItem(key), state.key);
    const recovery = await context.newPage();
    try {
      await recovery.goto(`${BASE}/laboratorio`);
      await recovery.evaluate(key => localStorage.setItem(key, '{'), state.key);
      await recovery.goto(`${BASE}${savedPath}`);
      await recovery.getByRole('alert').filter({ hasText: 'não puderam ser lidos' }).waitFor();
      await recovery.evaluate(({ key, raw }) => localStorage.setItem(key, raw), { key: state.key, raw });
      await recovery.getByRole('button', { name: 'Recarregar páginas locais', exact: true }).click();
      await expect(recovery.getByTestId('lab-page-name')).toHaveValue('Meu painel local');
      await expect(recovery.getByLabel('Nome do visitante', { exact: true })).toBeVisible();
    } finally { await recovery.close(); }
    await page.getByTestId('lab-menu-name').fill('Favoritos');
    await page.getByRole('button', { name: 'Adicionar ao menu informado', exact: true }).click();
    await page.waitForFunction((key) => JSON.parse(localStorage.getItem(key)).menus.length === 2, state.key);
    assert.equal(await page.getByTestId('lab-library-page').count(), 1);
    assert.equal(await page.locator('.praxis-shell__nav').getByRole('link', { name: /Meu painel local/ }).count(), 2);
    await page.locator('#praxis-main-content').evaluate(element => element.scrollTop = 0);
    await page.screenshot({ path: '/tmp/hero-visitor-lab-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    const closeNav = page.getByRole('button', { name: 'Fechar navegação', exact: true });
    await expect(closeNav).not.toBeInViewport();
    await page.getByTestId('lab-save').scrollIntoViewIfNeeded();
    assert.equal(await page.getByTestId('lab-save').isVisible(), true);
    await page.screenshot({ path: '/tmp/hero-visitor-lab-narrow.png', fullPage: true });
    await page.getByTestId('persona-switcher').click();
    await page.getByTestId('persona-option-tony.stark').click();
    await page.getByText('Esta página não existe neste navegador e persona.', { exact: false }).waitFor();
    await page.getByTestId('persona-switcher').click();
    await page.getByTestId('persona-option-nick.fury').click();
    await page.getByTestId('lab-page-name').waitFor();
    await expect(page.getByTestId('lab-page-name')).toHaveValue('Meu painel local');
    await page.getByRole('button', { name: 'Configurar conteúdo', exact: true }).click();
    await page.screenshot({ path: '/tmp/hero-visitor-lab-editor-narrow.png', fullPage: true });
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
    await page.getByTestId('lab-page-name').fill('Minha cópia editada');
    await page.getByTestId('lab-save').click();
    await page.getByTestId('lab-saved-link').waitFor();
    const copyPath = await page.getByTestId('lab-saved-link').getAttribute('href');
    assert.notEqual(copyPath, savedPath);
    const copied = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), state.key);
    assert.equal(copied.pages.length, 2);
    assert.deepEqual(copied.pages.find(item => item.id === state.value.pages[0].id).definition, state.value.pages[0].definition);
    page.once('dialog', dialog => dialog.accept());
    await page.getByTestId('lab-library-page').filter({ hasText: 'Minha cópia editada' }).getByRole('button', { name: 'Excluir página', exact: true }).click();
    await expect(page.getByTestId('lab-library-page')).toHaveCount(1);
    const renamedMenu = page.locator('.menu-row').first();
    await renamedMenu.locator('input').fill('Meu menu renomeado');
    await renamedMenu.getByRole('button', { name: 'Renomear menu', exact: true }).click();
    await expect(page.locator('.praxis-shell__nav-group-title').filter({ hasText: 'Meu menu renomeado' })).toHaveCount(1);
    page.once('dialog', dialog => dialog.accept());
    await page.locator('.menu-row').last().getByRole('button', { name: 'Remover menu', exact: true }).click();
    await expect(page.locator('.menu-row')).toHaveCount(1);
    await page.reload();
    await expect(page.locator('.menu-row input')).toHaveValue('Meu menu renomeado');
    const finalState = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), state.key);
    assert.equal(finalState.pages.length, 1);
    assert.ok(finalState.menus.every(menu => menu.items.every(item => finalState.pages.some(saved => saved.id === item.pageId))));
    // Direct widget settings use the same scoped storage, including panels opened without the builder bridge.
    await page.getByRole('button', { name: 'Configurar formulário', exact: true }).click();
    await page.getByRole('combobox', { name: 'Seção do editor' }).click();
    await page.getByRole('option', { name: 'JSON', exact: true }).click();
    const preferences = JSON.parse(await page.locator('textarea').inputValue());
    preferences.config.fieldMetadata[0].label = 'Nome ajustado no navegador';
    await page.locator('textarea').fill(JSON.stringify(preferences, null, 2));
    const applyPreferences = page.getByRole('button', { name: 'Aplicar JSON', exact: true });
    await expect(applyPreferences).toBeEnabled();
    await applyPreferences.focus();
    await applyPreferences.press('Enter');
    await page.getByRole('button', { name: 'Salvar e fechar', exact: true }).click();
    await expect(page.getByLabel('Nome ajustado no navegador', { exact: true })).toBeVisible();
    await page.waitForFunction(() => Object.keys(localStorage).some(key => key.startsWith('hero-hq:visitor-config:')));
    assert.equal(writes.length, 0, 'Visitor lab never writes remote configuration');
    console.log('PASS: canonical form editor apply/save -> field render -> quota recovery -> corrupt recovery -> real palette -> local atomic page/menu save -> route/reload -> second menu without duplicate -> persona A/B/A isolation -> copy preserves original -> rename/remove menus/delete copy -> direct form preferences local -> desktop/narrow; zero remote config writes.');
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
